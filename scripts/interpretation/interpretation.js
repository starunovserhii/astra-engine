// долгота -> знак + градус внутри знака (для точек, которых нет в DATA.points, напр. Асцендента/MC)
function lonToSignDeg(lon) {
  const norm = ((lon % 360) + 360) % 360;
  const idx = Math.floor(norm / 30);
  return { sign: SIGNS[idx], degreeInSign: Number((norm - idx * 30).toFixed(2)) };
}

function houseBasis(houseNum) {
  return houseNum ? ` (${houseNum}-й дом — ${HOUSE_THEME[houseNum].title})` : '';
}

// Абзац "планета в знаке [в доме]" — ядро расшифровки
function describePlanet(planetName, sign, houseNum, dignity, retro) {
  const interp = PLANET_INTERPRETERS[planetName];
  const nameRu = PLANET_NAME_RU[planetName] || planetName;
  const signRu = SIGN_NAME_RU[sign] || sign;
  const s = ZODIAC_TRAITS[sign];
  let text;
  if (interp) {
    text = interp.paragraph(s);
  } else if (MINOR_POINT_NOTE[planetName]) {
    text = MINOR_POINT_NOTE[planetName];
  } else {
    text = `${nameRu} в ${signRu} привносит в карту качества этого знака: ${s.core}.`;
  }
  if (houseNum && HOUSE_THEME[houseNum]) {
    text += ` Сильнее всего это заметно в сфере, за которую отвечает ${houseNum}-й дом — ${HOUSE_THEME[houseNum].title} (${HOUSE_THEME[houseNum].text}).`;
  }
  if (dignity && DIGNITY_MODIFIER[dignity]) {
    text += ' ' + DIGNITY_MODIFIER[dignity](nameRu);
  }
  if (retro) {
    text += ` Ретроградность ${nameRu.toLowerCase()} добавляет оттенок обращённости внутрь: энергия этой планеты чаще разворачивается не наружу сразу, а через переосмысление, прежде чем проявиться вовне.`;
  }
  return text;
}

function basisLine(...parts) {
  return 'На основе: ' + parts.filter(Boolean).join(', ') + '.';
}

